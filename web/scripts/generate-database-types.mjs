import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdir, writeFile, rename, readFile } from 'node:fs/promises';
import path from 'node:path';
import { projectRoot, testConnectionString } from './database-test-support.mjs';

const require=createRequire(import.meta.url);
const cli=require.resolve('supabase/dist/supabase.js');
const args=['gen','types','typescript','--schema','public'];
if (process.argv.includes('--test-database')) {
  const url=new URL(testConnectionString()); url.searchParams.set('sslmode','disable');
  args.push('--db-url',url.href);
}
else args.push('--local');
const child=spawn(process.execPath,[cli,...args],{cwd:projectRoot,windowsHide:true,stdio:['ignore','pipe','pipe']});
let output='',error='';
child.stdout.on('data',chunk=>{output+=chunk;});
child.stderr.on('data',chunk=>{error+=chunk;});
const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',resolve);});
if (code!==0 || !output.includes('export type Database')) {
  const safe=(error+'\n'+output).replace(/postgres(?:ql)?:\/\/[^\s]+/g,'[database URL redacted]');
  throw new Error(`Type generation failed (${code}). ${safe.slice(-1500)}`);
}
const target=path.join(projectRoot,'lib/database.types.ts');
const content='// Generated by Supabase CLI from the migrated database. Do not edit.\n'+output;
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8')!==content) throw new Error('Database types are stale. Run npm run db:types.');
  console.log('Database types match the migrated schema.');
} else {
  await mkdir(path.dirname(target),{recursive:true});
  await writeFile(target+'.tmp',content,'utf8');
  await rename(target+'.tmp',target);
  console.log('Generated lib/database.types.ts from the migrated schema.');
}
